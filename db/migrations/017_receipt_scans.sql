-- 017 — the scanned copy of an expense receipt (Q-51 answered, D-100)
--
-- The expense register holds the number printed on the paper and whether the paper is in the file.
-- Both are claims an auditor has to take on trust. This table is the index to the image itself.
--
-- Why the image is not in this table: the owner's answer was a folder on the office machine beside
-- the database, kept three years, backed up nightly by the office. So the bytes live in that folder
-- and this row is the index — which expense, which file on disk, what kind, how big, its fingerprint,
-- who filed it. A backup then carries a small table and a folder that is copied on its own schedule,
-- and a restore that forgets the folder is visibly wrong rather than silently empty.
--
-- Three invariants the database holds by itself:
--   * **one scan on file per expense** — a partial unique index, so two rows can never both claim to
--     be the current scan of one receipt;
--   * **a scan is never deleted** — removing it marks it removed, with a reason and a time, and the
--     file stays in the folder until its retention date. "Why is there no scan on this expense?" has
--     an answer a year later;
--   * **a removed scan stays removed** — the reason and the time are not rewritten afterwards.
--
-- `stored_name` is generated by the server and never comes from a person's typing: it is the name of
-- a file inside the folder, and a name a human chooses is how a path leaves that folder.

create table if not exists receipt_file (
  id               text primary key,
  expense_id       text not null references expense (id),
  stored_name      text not null unique check (stored_name ~ '^rcpt_[A-Za-z0-9._-]{8,80}$'),
  original_name    text not null check (length(original_name) between 1 and 160),
  mime_type        text not null check (mime_type in ('application/pdf','image/jpeg','image/png','image/webp')),
  byte_size        integer not null check (byte_size > 0 and byte_size <= 2097152),
  sha256           text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  status           text not null check (status in ('attached','removed')),
  removed_reason   text,
  removed_by       text,
  removed_at       timestamptz,
  -- Deferred: a replacement points at a scan inserted in the same transaction, and the scan it
  -- replaces has to be marked removed first so the unique index above still holds mid-transaction.
  superseded_by_id text references receipt_file (id) deferrable initially deferred,
  uploaded_by      text not null,
  uploaded_at      timestamptz not null,
  data             jsonb not null,
  constraint receipt_removed_has_reason
    check (status <> 'removed' or (removed_reason is not null and length(removed_reason) > 0)),
  constraint receipt_removed_has_time
    check (status <> 'removed' or removed_at is not null)
);

-- One current scan per expense. Removed rows are out of the way of this rule, which is what lets a
-- replacement be filed without deleting the scan it replaces.
create unique index if not exists receipt_file_attached_uq
  on receipt_file (expense_id) where status = 'attached';

create index if not exists receipt_file_expense_idx on receipt_file (expense_id);

-- ---------------------------------------------------------------- immutability

create or replace function receipt_file_frozen() returns trigger
language plpgsql as $$
begin
  if new.expense_id    is distinct from old.expense_id
  or new.stored_name   is distinct from old.stored_name
  or new.original_name is distinct from old.original_name
  or new.mime_type     is distinct from old.mime_type
  or new.byte_size     is distinct from old.byte_size
  or new.sha256        is distinct from old.sha256
  or new.uploaded_by   is distinct from old.uploaded_by
  or new.uploaded_at   is distinct from old.uploaded_at then
    raise exception 'A filed scan is immutable: remove it and file the correct one.'
      using errcode = '23514';
  end if;

  if old.status = 'removed' and new.status <> 'removed' then
    raise exception 'A removed scan stays removed; file a new one instead.'
      using errcode = '23514';
  end if;

  if old.status = 'removed'
     and (new.removed_reason is distinct from old.removed_reason or new.removed_at is distinct from old.removed_at) then
    raise exception 'A removed scan keeps its reason and the time it was removed.'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

drop trigger if exists receipt_file_frozen_trg on receipt_file;
create trigger receipt_file_frozen_trg before update on receipt_file
for each row execute function receipt_file_frozen();

create or replace function receipt_file_no_delete() returns trigger
language plpgsql as $$
begin
  raise exception 'A filed scan is never deleted; remove it with a reason (brief 5.9).';
end;
$$;

drop trigger if exists receipt_file_no_delete_trg on receipt_file;
create trigger receipt_file_no_delete_trg before delete on receipt_file
for each row execute function receipt_file_no_delete();

comment on table receipt_file is
  'The index to a receipt scan on the office disk: which expense, which file, its fingerprint and who filed it (D-100).';
